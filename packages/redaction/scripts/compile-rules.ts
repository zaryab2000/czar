// Build step (T-008, CZ-26 §3): compiles the vendored gitleaks v8.30.1 rule file into
// src/generated/gitleaks-rules.ts. A rule that cannot be translated exactly fails the build.
// Usage: node scripts/compile-rules.ts [--check]   (--check fails if the committed file is stale)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";
import { translateRe2 } from "@czar/redaction/re2";

const VENDOR = fileURLToPath(new URL("../vendor/gitleaks-v8.30.1/gitleaks.toml", import.meta.url));
const OUT = fileURLToPath(new URL("../src/generated/gitleaks-rules.ts", import.meta.url));
/** sha256 of config/gitleaks.toml at gitleaks tag v8.30.1 (C2-06). */
const EXPECTED_SHA256 = "e163e53b9e7e8a8511e77271e2b323ed057759542a6d988258afe3a1fa329caf";
const EXPECTED_RULES = 222;

interface TomlAllowlist {
  condition?: string;
  regexTarget?: string;
  regexes?: string[];
  stopwords?: string[];
  paths?: string[];
  commits?: string[];
}
interface TomlRule {
  id: string;
  description: string;
  regex?: string;
  path?: string;
  keywords?: string[];
  entropy?: number;
  secretGroup?: number;
  allowlists?: TomlAllowlist[];
}

const raw = readFileSync(VENDOR, "utf8");
const digest = createHash("sha256").update(raw).digest("hex");
if (digest !== EXPECTED_SHA256)
  throw new Error(`vendored gitleaks.toml sha256 ${digest} is not the pinned v8.30.1 file`);
const toml = parse(raw) as unknown as { allowlist: TomlAllowlist; rules: TomlRule[] };
if (toml.rules.length !== EXPECTED_RULES)
  throw new Error(`expected ${EXPECTED_RULES} rules, found ${toml.rules.length}`);

const allowlist = (a: TomlAllowlist) => ({
  condition: a.condition === "AND" ? "AND" : "OR",
  target: a.regexTarget === "match" || a.regexTarget === "line" ? a.regexTarget : "secret",
  regexes: (a.regexes ?? []).map(translateRe2),
  stopwords: [...new Set((a.stopwords ?? []).map((word) => word.toLowerCase()))],
  // Paths and commits cannot match a text without a file or commit (layer 1 scans text only).
  hasPathOrCommitCheck: (a.paths ?? []).length > 0 || (a.commits ?? []).length > 0,
});

const rules = toml.rules.map((rule) => ({
  id: rule.id,
  description: rule.description,
  regex: rule.regex === undefined ? null : translateRe2(rule.regex),
  // Rules gated on a file path never fire on plain text (gitleaks detect.go detectRule).
  pathRule: rule.path !== undefined,
  keywords: [...new Set((rule.keywords ?? []).map((keyword) => keyword.toLowerCase()))],
  entropy: rule.entropy ?? 0,
  secretGroup: rule.secretGroup ?? 0,
  allowlists: (rule.allowlists ?? []).map(allowlist),
}));

const globalAllowlist = allowlist({ ...toml.allowlist, paths: [] });

const source = `// GENERATED by scripts/compile-rules.ts from vendor/gitleaks-v8.30.1/gitleaks.toml (MIT). Do not edit.
// sha256 ${EXPECTED_SHA256}
import type { CompiledAllowlist, CompiledRule } from "../types.ts";

export const GITLEAKS_VERSION = "v8.30.1";

export const GLOBAL_ALLOWLIST: CompiledAllowlist = ${JSON.stringify(globalAllowlist)};

export const RULES: readonly CompiledRule[] = ${JSON.stringify(rules, null, 1)};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== source) {
    process.stderr.write("src/generated/gitleaks-rules.ts is stale; run pnpm compile-rules\n");
    process.exit(1);
  }
} else {
  writeFileSync(OUT, source);
  process.stdout.write(`compiled ${rules.length} rules\n`);
}
